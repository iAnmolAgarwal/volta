"""Tiny Markdown report writer shared by the analysis scripts."""

from pathlib import Path

import pandas as pd


def md_table(df: pd.DataFrame, floatfmt: str = ".2f", index: bool = True) -> str:
    """Render a DataFrame as a GitHub Markdown table (no tabulate dependency)."""
    if index:
        df = df.reset_index(names=df.index.name or "")

    def fmt(v):
        if isinstance(v, float):
            return format(v, floatfmt)
        return str(v)

    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    rule = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


class Report:
    """Collects Markdown blocks, echoes them to stdout, then writes one file."""

    def __init__(self, title: str, command: str):
        self.blocks = [f"# {title}", f"Generated by `{command}`. Do not edit by hand."]

    def add(self, *blocks: str) -> None:
        for block in blocks:
            print(block, end="\n\n", flush=True)
            self.blocks.append(block)

    def table(self, df: pd.DataFrame, **kwargs) -> None:
        self.add(md_table(df, **kwargs))

    def write(self, path: Path) -> None:
        path.write_text("\n\n".join(self.blocks) + "\n")
        print(f"Wrote {path}")
